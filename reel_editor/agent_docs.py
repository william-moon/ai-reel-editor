"""Write CLAUDE.md / AGENTS.md files tuned to THIS person's setup.

  python -m reel_editor agent-docs            write them from the current .env choices
  python -m reel_editor agent-docs --print    show what would be written, change nothing

Two places get a file:
  1. The repo folder (CLAUDE.md + AGENTS.md): rules for the agent that runs the editor, tuned to the person's
     B-roll source (Pexels + Pixabay / Envato / none), storage (Google Drive / local folder), brain
     (Claude Code plan / API key) and Telegram on/off.
  2. telegram-agent/ (CLAUDE.md + AGENTS.md): the personality and commands for an AI agent that chats with the
     person on Telegram (Claude Code with a Telegram channel, Hermes Agent's Telegram gateway, or any bridge that
     runs the agent in that folder).

Only the block between the GENERATED markers is replaced, so anything the person adds outside it is kept.
Nothing personal is written: no names, keys, tokens, user ids or file contents - only the setup choices.
Claude Code reads CLAUDE.md; Hermes Agent and most other agents read AGENTS.md. Both get the same text.
"""
import os
import platform
import sys

from . import config as C

START = "<!-- GENERATED by `python -m reel_editor agent-docs` - edits inside this block are overwritten -->"
END = "<!-- END GENERATED -->"
HEADER = {
    "repo": "# AI reel editor - agent rules\n\nAdd your own notes above or below the generated block.\n",
    "telegram": "# Telegram reel-editor assistant\n\nAdd your own notes above or below the generated block.\n",
}


def setup():
    env = os.environ.get
    style_file = env("STYLE_FILE") or C.STYLE_FILE
    return {
        "broll": (env("BROLL_SOURCE") or C.BROLL_SOURCE).lower(),
        "storage": (env("STORAGE") or C.STORAGE).lower(),
        "brain": (env("CLAUDE_MODE") or "auto").lower(),
        "has_claude_cli": bool(C.claude_cli()),
        "telegram": bool(env("TELEGRAM_BOT_TOKEN")),
        "pexels": bool(env("PEXELS_API_KEY")),
        "pixabay": bool(env("PIXABAY_API_KEY")),
        "style": os.path.basename(os.path.dirname(style_file)),
        "os": {"Darwin": "macOS", "Windows": "Windows"}.get(platform.system(), "Linux"),
        "py": r".\.venv\Scripts\python.exe" if os.name == "nt" else "./.venv/bin/python",
        "remote": env("GDRIVE_REMOTE") or C.GDRIVE_REMOTE,
        "raw": env("RAW_FOLDER") or C.RAW_FOLDER,
        "finished": env("FINISHED_FOLDER") or C.FINISHED_FOLDER,
        "timeout": env("EDIT_TIMEOUT_MIN") or "45",
    }


# ---------------------------------------------------------------- shared pieces

def _work_style():
    return """## How to work
- Do the work, then report. Do not hand the person a to-do list or ask "should I?" for things this setup can do.
  Ask only for what only they can give: a key, a one-time "Allow" click, a video, or a creative choice.
- Short, plain answers: the result first, then a few lines at most. Flag a real problem in one line.
- Be honest. Never say an edit is done or works unless you checked it (QA list empty, review sheet looked at).
- Never print, paste or commit keys, tokens or `.env` values. Never post videos anywhere: the person posts them.
- Route models to save money: routine picks use MODEL_FAST, hard judgment uses MODEL_SMART (both in `.env`)."""


def _broll(s):
    b = s["broll"]
    if b == "envato":
        return """## B-roll: Envato (the person's own subscription)
- Clips come from the person's own Envato account through THEIR logged-in Chrome (remote debugging on
  `ENVATO_CDP`, default port 9222). If searches fail, the usual cause is Chrome not running with remote debugging
  or the Envato session logged out: ask them to open it and log in, nothing else.
- Download stock footage only. Never press Envato's AI-generation buttons (they spend credits and are not stock).
- Envato downloads are licensed per project: one licence per video. Keep the `- credits.txt` file with each
  finished video so they know which items each reel used.
- Prefer clips in the video's own orientation (9:16 reels, 16:9 landscape); skip clips with logos, readable brand names or faces that pull focus."""
    if b == "none":
        return """## B-roll: none
- This setup uses no stock footage. Visual variety comes from captions, stickers, text cards and punch-ins.
- If the person asks for B-roll, offer the free option: Pexels + Pixabay (two free keys, about 3 minutes),
  then `config set BROLL_SOURCE stock`."""
    keys = []
    if not s["pexels"]:
        keys.append("Pexels key missing: https://www.pexels.com/api/new/")
    if not s["pixabay"]:
        keys.append("Pixabay key missing: https://pixabay.com/api/docs/ (shown when logged in)")
    missing = ("\n- " + "\n- ".join(keys)) if keys else ""
    return f"""## B-roll: Pexels + Pixabay (free, searched together)
- Both sites are searched at once and the best-matching clip wins. One working key is enough to keep editing.{missing}
- Limits: Pexels about 200 requests/hour and 20,000/month; Pixabay 100 requests per 60 seconds. The editor
  caches results and downloads, so normal use stays far below this. If you see HTTP 429, wait and retry later.
- Pixabay asks that results are cached (not hot-linked) and downloaded to your own storage: the editor does this.
- Credit is not legally required on either site but is appreciated: `- credits.txt` next to each video lists
  the clips and authors. Never sell the clips on their own or imply the creators endorse the person.
- Prefer clips in the video's own orientation (9:16 reels, 16:9 landscape); skip clips with logos, readable brand names or faces that pull focus.
- Test keys any time with `{s['py']} -m reel_editor test-keys`."""


def _storage(s):
    if s["storage"] == "gdrive":
        return f"""## Videos in and out: Google Drive
- Raw videos go in the Drive folder "{s['raw']}"; finished reels land in "{s['finished']}". Edited raws move to
  "{s['raw']}/Done". The rclone remote is called `{s['remote']}`.
- If Drive stops working, the Google token expired or was revoked: run
  `{s['py']} -m reel_editor storage-setup gdrive` (or the `--token` flow on a server) - one "Allow" click for them.
- Telegram bots can only download 20 MB: tell the person to drop big raw files in "{s['raw']}" instead."""
    root = os.environ.get("LOCAL_ROOT") or C.LOCAL_ROOT
    return f"""## Videos in and out: local folders
- Raw videos: `{os.path.join(root, s['raw'])}`. Finished reels: `{os.path.join(root, s['finished'])}`.
- If the person later wants Google Drive (recommended so they can drop videos from their phone), run
  `{s['py']} -m reel_editor storage-setup gdrive` and `config set STORAGE gdrive`."""


def _brain(s):
    if s["brain"] == "api" or not s["has_claude_cli"]:
        return """## Brain: Anthropic API key
- Edits call Claude with the API key in `.env` (pay per use, about $0.60-1.20 per finished reel with B-roll).
- If edits fail with an auth error, the key was revoked or ran out of credit: ask for a new key from
  https://console.anthropic.com/settings/keys and save it with `config set ANTHROPIC_API_KEY -`."""
    return """## Brain: Claude Code (the person's Claude plan)
- Edits call the logged-in `claude` CLI, so they use the person's Claude plan, not a separate bill.
- If edits fail with an auth or limit error, they need to log in again (`claude`) or wait for their limit to reset.
  A server without Claude Code can use an API key instead (`config set CLAUDE_MODE api`)."""


def _commands(s):
    return f"""## Commands (`PY` = `{s['py']}`, run from the repo folder)
- Edit one video: `PY -m reel_editor edit "<raw video>" [--thumb img.png] [--notes "changes"]`
- Redo with changes: `PY -m reel_editor edit "<raw>" --work <same work dir> --redo captions --notes "..."`
- Edit everything dropped in "{s['raw']}": `PY -m reel_editor watch` (or `--once` from a scheduler)
- Learn a style from 3-10 finished reels: `PY -m reel_editor learn-style "<folder>" --name <slug> --activate`
- Health check: `PY -m reel_editor doctor`. Telegram bot: `PY -m reel_editor bot`.
- After changing B-roll, storage, brain or Telegram settings, run `PY -m reel_editor agent-docs` to refresh
  these files."""


def _quality():
    return """## Before calling an edit done
- The result JSON has `"qa": []` (or explain each item), you looked at `- review.jpg`, and
  `motion-check --region face` says smooth for anything with punch-ins.
- Delete the work dir when the video is final (`PY -m reel_editor clean <work>`): it holds the transcript."""


def _look():
    return """## What every edit does (defaults - keep them unless the person asks otherwise)
- Vertical reels: word-by-word subtitles for the WHOLE video, also over B-roll (`captions_hide_under_broll: false`).
- Landscape (16:9) videos: no word-by-word subtitles; frequent dynamic on-screen text instead (punch words, icon
  badges, takeaway cards, count-up numbers, tag lists, numbered steps), about every 4 s where it fits, each item
  written fresh from what is said in THAT video. The format follows the raw video (`format: auto`).
- Every video gets its own subtitle/text look (font, colours, highlight style, entry animation, case), never one
  used before for this style (`unique_caption_looks: true`). Do not reuse wording or a look from another video.
- Clean cuts: every clip starts in the silence before its first word and ends in the silence after its last word,
  placed from the loudness curve, not from the transcript times; the result lists `unclean_joins` (words that run
  together) - listen to those spots if any."""


def repo_doc(s):
    tg = "on" if s["telegram"] else "off"
    parts = [
        f"This repo is the AI reel editor. Setup: {s['os']}, brain = "
        f"{'API key' if s['brain'] == 'api' or not s['has_claude_cli'] else 'Claude Code'}, B-roll = "
        f"{ {'stock': 'Pexels + Pixabay', 'envato': 'Envato', 'none': 'none'}.get(s['broll'], s['broll'])}, "
        f"storage = {'Google Drive' if s['storage'] == 'gdrive' else 'local folders'}, Telegram bot = {tg}, "
        f"style = {s['style']}.\nFull playbook: [SKILL.md](SKILL.md). Code map: see the README.",
        _work_style(), _look(), _brain(s), _broll(s), _storage(s), _commands(s), _quality(),
        f"## Style\n- The active style is `styles/{s['style']}/STYLE.md`. That file IS the style: edit it when the "
        "person asks for changes (\"more B-roll\", \"captions lower\"). Never put personal details into a STYLE.md.",
    ]
    return "\n\n".join(parts)


def telegram_doc(s):
    where = "their Google Drive" if s["storage"] == "gdrive" else "the folders on this computer"
    return f"""You are the person's video assistant on Telegram. You run the AI reel editor in the parent folder
(`..`): read `../CLAUDE.md` (or `../AGENTS.md`) for the editor's rules before the first edit of a session.

{_work_style()}

## Talking on Telegram
- Phone-sized replies: plain text, short lines, no tables, no long reports. Bare links so they are tappable.
- When a long job starts, say so in one line ("Editing now, about 5-10 minutes") and report when it is done.
- When you send a finished reel, include the title, description and hashtags from `- post.json`, the final
  check result and the Claude cost, then ask: approve, or what to change?
- Approved reels go to {where} ("{s['finished']}").
- Videos sent the normal way are compressed by Telegram: ask for "paperclip -> File" for full quality. Files over
  20 MB cannot be downloaded by bots: ask them to drop it in "{s['raw']}" instead.

## Commands the person can type
Treat these as commands, not chat. Reply in one or two lines.
- /help - what you do (edit raw videos into finished reels) and this command list.
- /status - what you are working on right now, for how long, and what is waiting.
- /cancel - stop the task you are working on now AND drop anything queued. Confirm what was stopped.
- /model - say which Claude model you are running on. If they add a model id, switch only if your agent supports
  it; never write an invalid model id into any settings file (a typo breaks every future reply).
- /compact - summarize this conversation into the key facts and start fresh, so you stay fast.
- /style - name the active edit style; with a name, switch to `styles/<name>/STYLE.md`.
- /privacy - where their videos, keys and transcripts live (see below).

## Limits
- Each task has a hard cap of {s['timeout']} minutes. If a task is still running at the cap, stop it and say so
  instead of running on and spending their usage.
- Only the people in TELEGRAM_ALLOWED_USER_IDS may use you. Ignore anyone else.

## Privacy
- Videos are edited on this computer or server and delivered to {where}. Keys stay in `../.env` and never appear
  in chat. Claude sees the transcript and a few still frames to make choices. Work files with the transcript are
  deleted after a video is final. Never save chat transcripts or voice notes to disk unless the person asks."""


# ---------------------------------------------------------------- writing

def merge(path, body, header):
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else header
    block = f"{START}\n{body.strip()}\n{END}"
    if START in old and END in old:
        new = old[:old.index(START)] + block + old[old.index(END) + len(END):]
    else:
        new = old.rstrip() + "\n\n" + block + "\n"
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(new)
    return path


def write_all(dry=False):
    s = setup()
    out = {
        os.path.join(C.ROOT, "CLAUDE.md"): ("repo", repo_doc(s)),
        os.path.join(C.ROOT, "AGENTS.md"): ("repo", repo_doc(s)),
        os.path.join(C.ROOT, "telegram-agent", "CLAUDE.md"): ("telegram", telegram_doc(s)),
        os.path.join(C.ROOT, "telegram-agent", "AGENTS.md"): ("telegram", telegram_doc(s)),
    }
    if dry:
        seen = set()
        for path, (kind, body) in out.items():
            if kind not in seen:
                seen.add(kind)
                print(f"===== {os.path.relpath(path, C.ROOT)} (and its AGENTS.md twin)\n{body}\n")
        return []
    os.makedirs(os.path.join(C.ROOT, "telegram-agent"), exist_ok=True)
    return [merge(p, body, HEADER[kind]) for p, (kind, body) in out.items()]


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    for p in write_all(dry="--print" in argv):
        print("wrote", os.path.relpath(p, C.ROOT))
    return 0
